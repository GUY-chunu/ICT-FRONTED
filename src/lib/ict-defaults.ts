function protocolFocus(day: number) {
  if (day <= 10) {
    const special: Record<number, string> = {
      1: "Write the weekly narrative. Mark PWH/PWL. Take nothing unless the model is obvious.",
      2: "Separate location from trigger. Journal the chain, not a paragraph.",
      4: "If you feel FOMO, you are already late. Skip.",
      7: "Weekly review: narrative errors vs execution errors.",
      10: "Survival check: still 0.25%? If yes, you are winning phase 1.",
    };
    return {
      title: `Survival · Day ${day}`,
      focus: special[day] ?? "Tiny size. One model. Stop after two losses.",
      riskPct: 0.25,
      maxTrades: 2,
      phase: 1 as const,
    };
  }
  if (day <= 20) {
    return {
      title: `Consistency · Day ${day}`,
      focus:
        day === 15
          ? "Expectancy check. If rule-follow < 90%, stay at 0.25%."
          : "Positive expectancy with controlled drawdown. Do not invent a new model.",
      riskPct: day >= 15 ? 0.35 : 0.25,
      maxTrades: 2,
      phase: 2 as const,
    };
  }
  if (day <= 26) {
    return {
      title: `Payout protection · Day ${day}`,
      focus: day === 21 ? "If the account is green, cut risk." : "Hold the line. No size-up.",
      riskPct: 0.25,
      maxTrades: 2,
      phase: 3 as const,
    };
  }
  const lock: Record<number, string> = {
    27: "Payout lock. Max 1 trade. Refuse heroics.",
    28: "If you are near the threshold, sit on your hands.",
    29: "Review the journal. One more clean day beats one more gamble.",
    30: "Lock. Request. Do not give it back on the last day.",
  };
  return {
    title: `Payout lock · Day ${day}`,
    focus: lock[day] ?? "Max one trade. Reduced risk.",
    riskPct: 0.2,
    maxTrades: 1,
    phase: 4 as const,
  };
}

export function buildProtocolDays(startDate: string): ProtocolDay[] {
  return Array.from({ length: 30 }, (_, i) => {
    const day = i + 1;
    const meta = protocolFocus(day);
    return {
      id: `day-${day}`,
      day,
      date: addDaysISO(startDate, i),
      title: meta.title,
      focus: meta.focus,
      phase: meta.phase,
      riskPct: meta.riskPct,
      maxTrades: meta.maxTrades,
      completed: false,
      skipped: false,
      notes: "",
    };
  });
}

